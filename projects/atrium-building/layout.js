export function doorPosition(item, opening) {
  const b = item.bounds;
  return {
    x: opening.side === "W" ? b.x1 : opening.side === "E" ? b.x2 : opening.at,
    z: opening.side === "N" ? b.z1 : opening.side === "S" ? b.z2 : opening.at,
  };
}
