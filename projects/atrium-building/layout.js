function room(
  prefix,
  code,
  name,
  category,
  bounds,
  furniture = "none",
  count = 0,
  doors = [],
  note = "",
) {
  return {
    id: `${prefix}-${code}`,
    name,
    category,
    bounds,
    furniture,
    count,
    doors,
    note,
    area:
      Math.round((bounds.x2 - bounds.x1) * (bounds.z2 - bounds.z1) * 10) / 10,
  };
}
